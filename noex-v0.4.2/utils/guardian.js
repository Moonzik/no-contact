/**
 * 从用户原话里摘一段「有信息量的片段」，用来在回复里复述。
 * 例：「我今天路过那家咖啡店了，好难受」→「路过那家咖啡店」
 */
function pickPhrase(text) {
  if (!text) return '';
  const s = String(text).replace(/\s+/g, '');
  if (!s) return '';

  /* 引号里的内容优先——那是用户自己强调的东西 */
  const quoted = s.match(/[「『“"'‘]([^」』”"'’]{1,14})[」』”"'’]/);
  if (quoted && quoted[1]) return quoted[1];

  /* 按标点切分，取最长的一句（信息量最大） */
  const segs = s.split(/[，。！？、；：,.!?;:~\-—…\n]/).filter((x) => x.length >= 3);
  let seg = segs.length ? segs[0] : s;
  for (let i = 0; i < segs.length; i++) {
    if (segs[i].length > seg.length) seg = segs[i];
  }

  /* 砍掉句首句尾的口水词 */
  let changed = true;
  while (changed && seg.length > 3) {
    changed = false;
    for (let i = 0; i < LEAD_STOP.length; i++) {
      if (seg.indexOf(LEAD_STOP[i]) === 0) {
        seg = seg.slice(LEAD_STOP[i].length);
        changed = true;
        break;
      }
    }
    for (let i = 0; i < TAIL_STOP.length; i++) {
      const w = TAIL_STOP[i];
      if (seg.length > w.length && seg.lastIndexOf(w) === seg.length - w.length) {
        seg = seg.slice(0, seg.length - w.length);
        changed = true;
        break;
      }
    }
  }

  if (seg.length > 13) seg = seg.slice(0, 13);
  /* 太短就没信息量，宁可不接话 */
  return seg.length >= 3 ? seg : '';
}


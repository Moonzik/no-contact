/* 随机取 */
function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

/* ── 全局去重（v0.7.0）─────────────────────────────────────────
   用户要求：清空数据 / 重置之前，小白的回复不能重复。
   做法：调用方把 S.usedReplies（一个 {句子:1} 的字典）传进来，
   每次取句都先过滤掉已用过的；一整句（主句+尾巴拼接后的完整文本）
   也参与去重，所以「同一主句换个尾巴」不会蒙混过关。
   某个池子全部用尽时，只清空**该池**的记录再循环（不会永久卡住）。
   ──────────────────────────────────────────────────────────── */

/* 从池子里挑一句「没用过的」；全用完了就清空该池记录重来 */
function pickUnused(pool, usedMap) {
  if (!pool || !pool.length) return '';
  if (!usedMap) return pick(pool);
  const avail = [];
  for (let i = 0; i < pool.length; i++) {
    if (!usedMap[pool[i]]) avail.push(pool[i]);
  }
  if (!avail.length) {
    for (let i = 0; i < pool.length; i++) delete usedMap[pool[i]];
    return pick(pool);
  }
  return pick(avail);
}

/* 把用过的句子记下来 */
function markUsed(usedMap, arr) {
  if (!usedMap) return;
  for (let i = 0; i < arr.length; i++) {
    if (arr[i]) usedMap[arr[i]] = 1;
  }
  /* 容量保护：字典太大就整体清空（等于重新一轮，不会崩存储） */
  let n = 0;
  for (const k in usedMap) { n++; if (n > USED_CAP) break; }
  if (n > USED_CAP) {
    for (const k in usedMap) delete usedMap[k];
  }
}

/* ① 主句 + ② 人格尾巴（整句参与去重） */
function buildMain(intent, p, usedMap, topic, hookPool) {
  const parts = [];
  const wantTail = shouldAddTail(p, intent);
  if (p === 'sharp') {
    /* 优先级：情绪意图 > 关键词钩子 > 日常话题 > 通用兜底 */
    let sp = SHARP_FALLBACK;
    if (intent && SHARP_POOL[intent]) sp = SHARP_POOL[intent];
    else if (hookPool) sp = hookPool;
    else if (topic && TOPIC_POOL.sharp[topic]) sp = TOPIC_POOL.sharp[topic];
    parts.push(pickUnused(sp, usedMap));
  } else {
    let pool = FALLBACK;
    if (intent && INTENT_POOL[intent]) pool = INTENT_POOL[intent];
    else if (hookPool) pool = hookPool;
    else if (topic && TOPIC_POOL.warm[topic]) pool = TOPIC_POOL.warm[topic];
    parts.push(pickUnused(pool, usedMap));
  }
  if (!wantTail) return parts;

  if (p === 'sharp') {
    /* v0.9.3：聊感情才用「戳 TA」的尾巴，聊别的用通用毒舌 */
    const tp = (intent && EX_INTENTS.indexOf(intent) > -1) ? SHARP_TAILS : SHARP_TAILS_GENERAL;
    parts.push(pickUnused(tp, usedMap));
  } else if (p === 'warm') {
    const tp = (intent && EX_INTENTS.indexOf(intent) > -1) ? WARM_TAILS : WARM_TAILS_GENERAL;
    parts.push(pickUnused(tp, usedMap));
  } else if (p === 'tsun') {
    const tp = (intent && EX_INTENTS.indexOf(intent) > -1) ? TSUN_TAILS : TSUN_TAILS_GENERAL;
    parts.push(pickUnused(tp, usedMap));
  }
  else if (p === 'spoil') {
    /* v0.9.4：撒娇尾巴同样分档，聊日常时不提 TA */
    const tp = (intent && EX_INTENTS.indexOf(intent) > -1) ? SPOIL_TAILS : SPOIL_TAILS_GENERAL;
    parts.push(pickUnused(tp, usedMap));
  }

  /* 主句和尾巴可能抽到同一句（两句池子有交集），读起来就是「同一句话说两遍」。
     最多重摇 3 次，实在撞就砍掉尾巴。 */
  for (let k = 0; k < 3 && parts.length > 1 && parts[parts.length - 1] === parts[0]; k++) {
    parts.pop();
    const tp2 = tailPool(p, intent);
    if (!tp2) break;
    parts.push(pickUnused(tp2, usedMap));
  }
  if (parts.length > 1 && parts[parts.length - 1] === parts[0]) parts.pop();
  return parts;
}

/* v0.9.5 · 尾巴不再每次都挂。
   以前每条回复 = 主句 + 尾巴，像盖章一样回回带一句「我陪着你」「别绕圈子说重点」，
   读起来是在演人设，不自然。现在按概率挂：
   聊情绪时多一点（那种时候需要陪伴感），聊日常/具体事时少一点，让对话更像正常人说话。
   人格本身还在——主句来自各人格专属的池子，不会因此变得平淡。 */
const TAIL_RATE = { warm: 0.35, sharp: 0.5, tsun: 0.45, spoil: 0.5 };

function shouldAddTail(p, intent) {
  const base = (TAIL_RATE[p] != null) ? TAIL_RATE[p] : 0.4;
  const bonus = (intent && EX_INTENTS.indexOf(intent) > -1) ? 0.3 : 0;
  return Math.random() < base + bonus;
}

/* 取当前人格/意图对应的尾巴池，供去重重摇用 */
function tailPool(p, intent) {
  if (p === 'sharp') {
    return (intent && EX_INTENTS.indexOf(intent) > -1) ? SHARP_TAILS : SHARP_TAILS_GENERAL;
  }
  if (p === 'warm') return (intent && EX_INTENTS.indexOf(intent) > -1) ? WARM_TAILS : WARM_TAILS_GENERAL;
  if (p === 'tsun') return (intent && EX_INTENTS.indexOf(intent) > -1) ? TSUN_TAILS : TSUN_TAILS_GENERAL;
  if (p === 'spoil') {
    return (intent && EX_INTENTS.indexOf(intent) > -1) ? SPOIL_TAILS : SPOIL_TAILS_GENERAL;
  }
  return null;
}

/* ③ v0.8.1 接话：复述用户原话里的具体片段，让回复"对得上这一句"。
      - 没识别出意图时必接（否则就是一句空泛的「然后呢」）
      - 识别出意图时按概率接，避免每条都太长
      - **模板**参与判重（避免句式重复），但**生成出来的整句不写进 used**：
        用户每句话都不同，接话几乎必然唯一，写进去会把 600 容量的字典冲光，
        反而让主句的去重失效。 */
function buildFollowUp(intent, p, text, usedMap, topic, hookPool) {
  const phrase = pickPhrase(text);
  if (!phrase) return '';
  /* v0.9.3：已经识别出意图、有针对性回复了，就不再额外补一段
     （以前 35% 概率还要再拼一句，读起来就是在硬凑内容）。
     只有「没识别出意图」时才接话——那种情况不接就等于「然后呢」，像没在听。 */
  if (intent || topic || hookPool) return '';
  const pool = FALLBACK_FOLLOW[p] || FALLBACK_FOLLOW.warm;
  const tpl = pickUnused(pool, usedMap);
  if (usedMap) usedMap[tpl] = 1;
  return ' ' + tpl.replace(/\$\{p\}/g, phrase);
}

/**
 * 生成守护者回复
 * @param {string} text 用户消息
 * @param {string} persona 当前人格 warm/sharp/tsun/spoil
 * @param {array}  bottle 留白瓶（用于 urge 时建议写入）
 * @param {object} usedMap 已使用句子字典（传 S.usedReplies，可选）
 * @returns {object} { crisis, text, intent }
 */
function guardianReply(text, persona, bottle, usedMap) {
  const used = usedMap || {};
  const intent = detectIntent(text);
  if (intent === 'crisis') {
    return { crisis: true, text: CRISIS_TEXT, intent };
  }
  const p = persona || 'warm';
  /* v0.9.4：只有命中**具体情绪**才走情绪池。
     daily 本身是「没识别出情绪」的兜底意图，此时如果能认出话题（加班/吃饭/下雨…），
     话题回复比一句泛泛的「你今天有在好好过日子」贴切得多，所以让话题优先。 */
  const topic = (intent && intent !== 'daily') ? null : detectTopic(text);
  /* v0.9.5：具体词钩子优先级最高（真实情绪除外）——说到旅游就回旅游，不再抽到「堵车」。
     daily 是「没识别出情绪」的兜底意图，不能挡住钩子，否则「周末有什么安排」这类就不生效。 */
  const hookPool = (intent && intent !== 'daily') ? null : pickHook(text, p);
  const effIntent = (topic || hookPool) ? null : intent;

  /* 最多试 16 次拼出一条「整句没出现过」的回复；实在拼不出就用最后一次 */
  let out = '';
  let parts = [];
  for (let i = 0; i < 16; i++) {
    parts = buildMain(effIntent, p, used, topic, hookPool);
    let cand = parts.join('');
    if (p !== 'sharp' && effIntent === 'urge' && bottle && bottle.length && Math.random() < 0.5) {
      cand += BOTTLE_TIP;
    }
    out = cand;
    if (!used[cand]) break;
  }

  markUsed(used, parts);
  used[out] = 1;

  return { crisis: false, text: out + buildFollowUp(effIntent, p, text, used, topic, hookPool), intent: intent || null, topic: topic || null, hook: !!hookPool };
}


/* 从用户输入里找命中的钩子池：命中多个时取**最长**的那个关键词。 */
function pickHook(text, p) {
  const arr = (p && HOOKS[p]) || HOOKS.warm;
  const t = String(text || '').replace(/\s+/g, '');
  let best = null;
  let bestLen = 0;
  for (let i = 0; i < arr.length; i++) {
    const keys = arr[i][0];
    for (let j = 0; j < keys.length; j++) {
      const k = keys[j];
      if (t.indexOf(k) > -1 && k.length > bestLen) {
        bestLen = k.length;
        best = arr[i][1];
      }
    }
  }
  return best;
}


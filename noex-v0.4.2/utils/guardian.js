/* 检测意图（命中第一个匹配的关键字所在类别） */
/**
 * 意图识别 v0.8.1：改成「打分制」。
 * 旧版是按对象顺序遍历、命中第一个就返回——一句话里同时有
 * 「睡不着」和「想他」时，谁写在前面就归谁，经常回错。
 * 现在：危机最高优先；其余按命中词数量 + 词长加权打分，取最高分。
 */
function detectIntent(text) {
  if (!text) return null;
  /* 去空白再匹配：用户打「想 ta」「睡 不着」带空格时，关键词表里的「想ta」匹配不上，
     意图会整个丢失，回复就掉进兜底池。中文里空格没有语义，去掉只会提高命中。 */
  const t = String(text).replace(/\s+/g, '');

  const crisisKeys = INTENT_KEYS.crisis || [];
  for (let i = 0; i < crisisKeys.length; i++) {
    if (t.indexOf(crisisKeys[i]) > -1) return 'crisis';
  }

  /* v0.9.4 · 「好想吃火锅 / 好想睡觉 / 好想辞职」里的「想」是想干某件事，不是想念某个人。
     只有明确指向人（想他/想她/想念/忘不了）才算 miss；
     「想 + 动词」一律不算，让它落到话题层去（吃饭/睡觉/工作）。 */
  const MISS_STRONG = /想他|想她|想ta|想TA|想念|想你们|想我们|忘不了|放不下|脑子里都是/i;
  const MISS_NEG =
    /想(吃|喝|睡|去|玩|买|看|回|走|做|干|点|要|学|练|打|撸|躺|坐|抱|养|换|试|说|问|哭|笑|吐|搬|洗|剪|约|考|开)/;

  let best = null;
  let bestScore = 0;
  for (const k in INTENT_KEYS) {
    if (k === 'crisis') continue;
    if (k === 'miss' && MISS_NEG.test(t) && !MISS_STRONG.test(t)) continue;
    const arr = INTENT_KEYS[k] || [];
    let score = 0;
    for (let i = 0; i < arr.length; i++) {
      if (t.indexOf(arr[i]) > -1) {
        /* 长词信息量大，权重高：「想发消息」比「想」更能说明意图 */
        score += arr[i].length >= 4 ? 4 : (arr[i].length >= 3 ? 3 : 1);
      }
    }
    if (score > bestScore) { bestScore = score; best = k; }
  }
  return best;
}

/* v0.9.4 · 日常话题识别：只在**没命中情绪意图**时调用 */
function detectTopic(text) {
  if (!text) return null;
  const t = String(text).replace(/\s+/g, '');
  let best = null;
  let bestScore = 0;
  for (const k in TOPIC_KEYS) {
    const arr = TOPIC_KEYS[k] || [];
    let score = 0;
    for (let i = 0; i < arr.length; i++) {
      if (t.indexOf(arr[i]) > -1) {
        score += arr[i].length >= 4 ? 4 : (arr[i].length >= 3 ? 3 : 1);
      }
    }
    if (score > bestScore) { bestScore = score; best = k; }
  }
  return best;
}


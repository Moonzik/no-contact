/* 字符串哈希（同一个日期永远得到同一个数） */
function hashStr(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = (h * 31 + s.charCodeAt(i)) % 1000000007;
  }
  return h;
}

/**
 * 取某一天的「每日一句」
 * @param {string} dateStr 'YYYY-MM-DD'
 * @param {object} usedMap 已用过的句子字典（可选，传 S.usedReplies 可以顺带去重）
 * @returns {string}
 */
function dailyQuote(dateStr, usedMap) {
  const n = DAILY_QUOTES.length;
  const start = hashStr(dateStr || '') % n;
  /* 从哈希位置往后找第一句「没用过的」——保证连续很多天都不重样 */
  for (let i = 0; i < n; i++) {
    const q = DAILY_QUOTES[(start + i) % n];
    if (!usedMap || !usedMap[q]) return q;
  }
  /* 全用过了：清空这些记录，从头再来 */
  if (usedMap) {
    for (let i = 0; i < n; i++) delete usedMap[DAILY_QUOTES[i]];
  }
  return DAILY_QUOTES[start];
}


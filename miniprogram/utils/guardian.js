const CRISIS_TEXT =
  '这句话让我停下来认真回复你：你现在的痛苦一定很重，重到我这个AI不该独自接住它。请让真实世界里的人，现在就陪着你。';

/* 检测意图（命中第一个匹配的关键字所在类别） */
function detectIntent(text) {
  for (const k in INTENT_KEYS) {
    const arr = INTENT_KEYS[k];
    for (let i = 0; i < arr.length; i++) {
      if (text.indexOf(arr[i]) > -1) return k;
    }
  }
  return null;
}

/* 随机取 */
function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

/**
 * 生成守护者回复
 * @param {string} text 用户消息
 * @param {string} persona 当前人格 warm/sharp/tsun/spoil
 * @param {array}  bottle 留白瓶（用于 urge 时建议写入）
 * @returns {object} { crisis, text, intent }
 */
function guardianReply(text, persona, bottle) {
  const intent = detectIntent(text);
  if (intent === 'crisis') {
    return { crisis: true, text: CRISIS_TEXT, intent };
  }
  const pool = intent ? (INTENT_POOL[intent] || FALLBACK) : FALLBACK;
  let base = pick(pool);
  const p = persona || 'warm';

  if (p === 'warm') {
    base = '嗯，我在。' + base + ' 你不用急，慢慢说。';
  } else if (p === 'sharp') {
    base = base + pick([
      ' 大半夜又翻聊天记录？脑子是不是进水了。',
      ' 第几次了，你这点出息自己心里没数吗。',
      ' 哭完记得擦脸，鼻涕眼泪糊一键盘没人给你擦。',
      ' 把手机放下。你这手怎么就不听使唤呢。',
      ' 行了行了，我知道了——你这不叫放下，叫手贱。',
      ' 看看表，几点了？明天顶着肿眼泡去上班是吧。'
    ]);
  } else if (p === 'tsun') {
    base = base + ' ……才不是心疼你呢。';
  } else if (p === 'spoil') {
    base = base + pick([
      ' 我才是今天最关心你的人。',
      ' 来，先看我，不要想 ta。',
      ' 你今天有想我吗？不管，我问了你就要想。',
      ' 我吃醋了，不许再提 ta。'
    ]);
  }

  if (intent === 'urge' && bottle && bottle.length && Math.random() < 0.5) {
    base += ' 如果话已经到嘴边了，就把它写进「留白瓶」吧——写下来，但不必发送。';
  }

  return { crisis: false, text: base, intent };
}


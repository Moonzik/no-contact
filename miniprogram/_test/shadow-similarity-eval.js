/* ============ 评估函数 ============ */

function profileReport(name, text) {
  const p = shadow.analyzeChat(text);
  console.log('\n┌─── ' + name + ' ───');
  console.log('│ 消息条数：' + p.count);
  console.log('│ 平均字数：' + p.avgLen);
  console.log('│ 爱用表情：' + (p.emojiLove ? '是' : '否'));
  console.log('│ 口头禅 top3：' + (p.top.length ? p.top.join(' / ') : '（无）'));
  console.log('│ 反问率：' + (p.qRate * 100).toFixed(1) + '%');
  console.log('│ 画像文案：');
  console.log(shadow.profileSummary(p).split('\n').map(l => '│   ' + l).join('\n'));
  console.log('└──────────────────────');
  return p;
}

function repliesForIntent(p, intent, text, count = 6) {
  console.log('\n  [' + intent + '] 触发文本：「' + text + '」');
  const seen = new Set();
  const samples = [];
  let tries = 0;
  while (samples.length < count && tries < 30) {
    const r = shadow.shadowReply(text, p);
    if (!seen.has(r)) {
      seen.add(r);
      samples.push(r);
    }
    tries++;
  }
  samples.forEach((s, i) => console.log('    ' + (i + 1) + '. ' + s));
  return samples;
}

function runSample(name, text) {
  console.log('\n══════════════════════════════════════════');
  console.log('  样本：' + name);
  console.log('══════════════════════════════════════════');
  const p = profileReport(name, text);

  /* 触发 5 种 intent + fallback */
  repliesForIntent(p, 'miss',  '我好想你',     5);
  repliesForIntent(p, 'ask',   '你为什么这样', 5);
  repliesForIntent(p, 'angry', '你凭什么',     5);
  repliesForIntent(p, 'bye',   '我要走了 再见', 5);
  repliesForIntent(p, 'greet', '在吗',         5);
  repliesForIntent(p, 'fallback', '今天晚饭不知道吃什么', 5);

  return p;
}

